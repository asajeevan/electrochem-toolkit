"""The property the whole layer exists to have.

For a file whose true capacity is known by construction, written in an
arbitrary combination of delimiter, decimal mark, encoding, byte-order mark,
preamble length, unit and sign convention, `read` must do exactly one of:

  a. raise ImportFailure, or
  b. return a table whose capacity equals the constructed truth.

It must never return a table with numbers that are merely plausible. A silent
wrong answer is the only outcome that is unacceptable, because it is the only
one a researcher cannot detect downstream.

This is run as a seeded sweep rather than with a property-testing library so
the prototype keeps its small dependency set, and so a failure is reproducible
from the printed seed alone.
"""
from __future__ import annotations

import itertools
import random
from pathlib import Path

import numpy as np
import pytest

from electrochem.readers.profile import UNIT_FACTOR, Binding, Conventions, ImportProfile, Layout
from electrochem.readers.reader import ImportFailure, read

# A constant-current charge then discharge: the capacity is exact arithmetic,
# not a numerical result, so any disagreement is a defect and not a tolerance.
I_A = 1.5e-3
T_CHARGE_S = 2400
T_DISCHARGE_S = 1200
DT = 30
TRUE_CHARGE_AH = I_A * T_CHARGE_S / 3600.0
TRUE_DISCHARGE_AH = I_A * T_DISCHARGE_S / 3600.0

TIME_UNITS = ["s", "min", "h"]
CURRENT_UNITS = ["A", "mA", "uA"]
ENCODINGS = ["utf-8", "cp1252", "utf-8-sig"]
DELIMITERS = ["\t", ",", ";"]


def _experiment() -> list[tuple[int, float, float, float]]:
    """(step, t_seconds, current_A charge-positive, voltage_V)."""
    rows, t = [], 0.0
    for step, (dur, cur) in enumerate(
            [(600, 0.0), (T_CHARGE_S, I_A), (600, 0.0), (T_DISCHARGE_S, -I_A)], start=1):
        for k in range(dur // DT + 1):
            rows.append((step, t + k * DT, cur, 3.0 + 0.5 * (k * DT) / max(dur, 1)))
        t += dur
    return rows


def _write(path: Path, *, delim: str, decimal: str, encoding: str, bom: bool,
           preamble: int, trailing: bool, t_unit: str, i_unit: str,
           discharge_positive: bool) -> None:
    tf, cf = UNIT_FACTOR[t_unit], UNIT_FACTOR[i_unit]
    flip = -1.0 if discharge_positive else 1.0

    def num(x: float) -> str:
        s = f"{x:.12g}"
        return s.replace(".", ",") if decimal == "," else s

    head = delim.join(["Step", f"Time({t_unit})", f"Current({i_unit})", "Voltage(V)"])
    if trailing:
        head += delim
    lines = [f"instrument preamble line {k}" for k in range(preamble)] + [head]
    for step, t, i, e in _experiment():
        lines.append(delim.join([str(step), num(t / tf), num(i * flip / cf), num(e)]))
    data = ("\n".join(lines) + "\n").encode(encoding)
    path.write_bytes((b"\xef\xbb\xbf" + data) if bom and encoding != "utf-8-sig" else data)


def _profile(*, delim: str, decimal: str, encoding: str, discharge_positive: bool,
             declare_decimal: bool) -> ImportProfile:
    return ImportProfile(
        name="fuzz", instrument="synthetic",
        layout=Layout(kind="delimited", encoding=encoding, delimiter=delim,
                      decimal=(decimal if declare_decimal else "auto"),
                      header_contains=("Voltage(V)",)),
        conventions=Conventions(
            current_sign="discharge_positive" if discharge_positive else "charge_positive",
            direction_source="current_sign", capacity_semantics="none", cycle_base=1,
            evidence="synthetic file generated by test_fuzz with a known capacity"),
        bindings={"test_time_second": Binding(source=("Time",)),
                  "current_ampere": Binding(source=("Current",)),
                  "voltage_volt": Binding(source=("Voltage",)),
                  "step_id": Binding(source=("Step",), source_unit="1")})


def _capacity(tab) -> tuple[float, float]:
    """Trapezoid within a step, as the engine does it."""
    h = np.diff(tab.t)
    q = h * (tab.i[:-1] + tab.i[1:]) / 2.0 / 3600.0
    q = np.where(tab.step_id[:-1] == tab.step_id[1:], q, 0.0)
    return float(q[q > 0].sum()), float(-q[q < 0].sum())


def _check(tmp_path: Path, name: str, **opts) -> str:
    """Return 'refused' or 'correct'; raise if the answer was wrong."""
    gen = {k: opts[k] for k in ("delim", "decimal", "encoding", "bom", "preamble",
                                "trailing", "t_unit", "i_unit", "discharge_positive")}
    p = tmp_path / name
    _write(p, **gen)
    try:
        tab = read(p, _profile(delim=opts["delim"], decimal=opts["decimal"],
                               encoding=opts["encoding"],
                               discharge_positive=opts["discharge_positive"],
                               declare_decimal=opts["declare_decimal"]))
    except ImportFailure:
        return "refused"
    qc, qd = _capacity(tab)
    assert qc == pytest.approx(TRUE_CHARGE_AH, rel=1e-9), f"charge wrong for {opts}"
    assert qd == pytest.approx(TRUE_DISCHARGE_AH, rel=1e-9), f"discharge wrong for {opts}"
    assert tab.i.max() > 0 and tab.i.min() < 0, f"sign not normalised for {opts}"
    return "correct"


# --------------------------------------------------------------- exhaustive
# Every combination of the choices that interact: delimiter against decimal
# mark, and units against sign convention. 'comma delimiter with decimal comma'
# is excluded, since the file is then genuinely ambiguous to any reader.
@pytest.mark.parametrize("delim,decimal", [(d, m) for d in DELIMITERS for m in (".", ",")
                                           if not (d == "," and m == ",")])
@pytest.mark.parametrize("t_unit,i_unit", list(zip(TIME_UNITS, CURRENT_UNITS)))
@pytest.mark.parametrize("discharge_positive", [False, True])
def test_units_delimiters_and_sign_conventions_are_all_exact(
        tmp_path, delim, decimal, t_unit, i_unit, discharge_positive):
    assert _check(tmp_path, "f.txt", delim=delim, decimal=decimal, encoding="utf-8",
                  bom=False, preamble=3, trailing=False, t_unit=t_unit, i_unit=i_unit,
                  discharge_positive=discharge_positive, declare_decimal=True) == "correct"


@pytest.mark.parametrize("encoding,bom,preamble,trailing",
                         list(itertools.product(ENCODINGS, [False, True], [0, 1, 7], [False, True])))
def test_encoding_bom_preamble_and_trailing_delimiter_are_all_exact(
        tmp_path, encoding, bom, preamble, trailing):
    assert _check(tmp_path, "g.txt", delim="\t", decimal=".", encoding=encoding, bom=bom,
                  preamble=preamble, trailing=trailing, t_unit="s", i_unit="A",
                  discharge_positive=False, declare_decimal=True) == "correct"


# ------------------------------------------------------------------- sweep
def test_a_randomised_sweep_never_produces_a_wrong_number(tmp_path):
    """200 random dialects. Each must be read exactly or refused outright."""
    rng = random.Random(20261019)
    outcomes = {"correct": 0, "refused": 0}
    for n in range(200):
        delim = rng.choice(DELIMITERS)
        decimal = rng.choice([".", ","])
        if delim == "," and decimal == ",":
            decimal = "."
        opts = dict(delim=delim, decimal=decimal, encoding=rng.choice(ENCODINGS),
                    bom=rng.random() < 0.3, preamble=rng.randint(0, 12),
                    trailing=rng.random() < 0.3, t_unit=rng.choice(TIME_UNITS),
                    i_unit=rng.choice(CURRENT_UNITS),
                    discharge_positive=rng.random() < 0.5,
                    declare_decimal=rng.random() < 0.5)
        try:
            outcomes[_check(tmp_path, f"s{n}.txt", **opts)] += 1
        except AssertionError as exc:
            raise AssertionError(f"wrong number for case {n}: {opts}") from exc
    # Refusals are acceptable, but a layer that refuses everything is useless.
    assert outcomes["correct"] >= 150, outcomes


# --------------------------------------------- remaining metamorphic relation
def test_appending_a_time_shifted_copy_doubles_the_capacity(tmp_path):
    """Duplicating the whole experiment with the clock carried forward and the
    step numbers continued must double every capacity and nothing else. This is
    the relation that catches an integration which depends on absolute position
    in the file rather than on the signal."""
    p, q = tmp_path / "once.txt", tmp_path / "twice.txt"
    _write(p, delim="\t", decimal=".", encoding="utf-8", bom=False, preamble=2,
           trailing=False, t_unit="s", i_unit="A", discharge_positive=False)
    lines = p.read_text().splitlines()
    head, body = lines[:3], lines[3:]
    last_t = float(body[-1].split("\t")[1])
    shifted = []
    for r in body:
        f = r.split("\t")
        f[0] = str(int(f[0]) + 4)
        f[1] = f"{float(f[1]) + last_t + DT:.12g}"
        shifted.append("\t".join(f))
    q.write_text("\n".join(head + body + shifted) + "\n")

    prof = _profile(delim="\t", decimal=".", encoding="utf-8",
                    discharge_positive=False, declare_decimal=True)
    a, b = _capacity(read(p, prof)), _capacity(read(q, prof))
    assert b[0] == pytest.approx(2 * a[0], rel=1e-9)
    assert b[1] == pytest.approx(2 * a[1], rel=1e-9)
